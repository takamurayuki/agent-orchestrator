import type { AskedQuestion, DecisionRecord, Fact, GeneratedArtifact, TaskProposal } from '@agent-orchestrator/contracts';

/**
 * 生成物（スクリプトで再生成されるファイル）の扱い（v0.2.1、D-41）。
 * - リポジトリ調査: package.json の scripts から生成スクリプト候補と生成先を推定し、生成ファイルのヘッダー（自動生成 / generated）から生成元を拾って facts にする
 * - 素案検証: generatedArtifacts の script が package.json に無ければ、推測せず承認前に blocking 質問（GEN-n）で生成手段を尋ねる
 * - 回答（判断）を素案に機械的に適用する（script の差し替え、または手動更新として除外）
 * 任意のシェルコマンドは扱わない: script は常に package.json の scripts 名。
 */
export const GENERATION_QUESTION_PREFIX = 'GEN-';
export const MANUAL_GENERATION = 'manual';

const SCRIPT_NAME_RE = /(^|[:_-])(gen|generate|report|docs?|schema|build:docs|codegen|snapshot|export)([:_-]|$)/i;
const OUTPUT_TOKEN_RE = /(?:^|\s|=|'|")((?:[\w.-]+\/)*[\w.-]+\.(?:md|json|ya?ml|ts|js|mjs|txt|csv|html|svg))(?=\s|$|'|")/g;
const GENERATED_HEADER_RE = /自動生成|auto-?generated|generated by|do not edit|generated file/i;
const SCRIPT_PATH_RE = /((?:scripts|tools|bin)\/[\w./-]+\.(?:mjs|cjs|js|ts))/;

export interface GenerationCandidate {
  script: string;
  command: string;
  outputs: string[];
}

/** package.json の scripts から生成スクリプト候補を推定する（名前と、コマンド中の出力ファイル名） */
export function detectGenerationScripts(scripts: Record<string, string>, files: readonly string[]): GenerationCandidate[] {
  const fileSet = new Set(files.map((f) => f.replace(/\\/g, '/')));
  const out: GenerationCandidate[] = [];
  for (const [name, command] of Object.entries(scripts)) {
    if (typeof command !== 'string') continue;
    const outputs = [...command.matchAll(OUTPUT_TOKEN_RE)].map((m) => m[1]!).filter((t) => fileSet.has(t) && !/^(scripts|tools|bin)\//.test(t));
    const named = SCRIPT_NAME_RE.test(name);
    if (!named && outputs.length === 0) continue;
    if (/^(test|lint|typecheck|build|dev|start|preview|format|clean)(:|$)/.test(name) && outputs.length === 0) continue;
    out.push({ script: name, command, outputs });
  }
  return out;
}

export interface GeneratedFileHint {
  path: string;
  /** ヘッダーに書かれた生成元スクリプトのパス（分かれば） */
  generator: string | null;
  /** 生成元を実行する package.json の script 名（分かれば） */
  script: string | null;
}

/** 生成ファイルの候補（*.generated.*、docs/*.md 等の先頭行に自動生成の記載があるもの）を調べる */
export function detectGeneratedFiles(files: readonly string[], readHead: (path: string) => string | null, scripts: Record<string, string>): GeneratedFileHint[] {
  const hints: GeneratedFileHint[] = [];
  const candidates = files.filter((f) => /\.generated\.|^docs\/.*\.md$|\.schema\.json$|^README\.md$/i.test(f)).slice(0, 60);
  for (const path of candidates) {
    const head = readHead(path);
    if (!head) continue;
    const firstLines = head.split(/\r?\n/).slice(0, 5).join('\n');
    if (!GENERATED_HEADER_RE.test(firstLines) && !/\.generated\./.test(path)) continue;
    const generator = SCRIPT_PATH_RE.exec(firstLines)?.[1] ?? null;
    let script: string | null = null;
    if (generator) {
      for (const [name, command] of Object.entries(scripts)) if (typeof command === 'string' && command.includes(generator)) script = name;
    }
    hints.push({ path, generator, script });
  }
  return hints;
}

export function generationFacts(candidates: readonly GenerationCandidate[], hints: readonly GeneratedFileHint[]): Fact[] {
  const facts: Fact[] = [];
  for (const c of candidates) facts.push({ key: 'generation.script', value: `${c.script} → ${c.command}${c.outputs.length ? `（出力: ${c.outputs.join(', ')}）` : ''}`, source: 'package.json#scripts', confidence: 'confirmed' });
  for (const h of hints) facts.push({ key: 'generated.file', value: `${h.path} は生成ファイル${h.generator ? `（生成元: ${h.generator}${h.script ? `、script: ${h.script}` : '、package.json の script なし'}）` : '（生成元のスクリプトは不明）'}。手で編集せず、生成元を直して再生成する`, source: h.path, confidence: h.generator ? 'confirmed' : 'inferred' });
  return facts;
}

/** 素案の generatedArtifacts のうち、script が package.json に無いもの */
export function unknownGenerationScripts(artifacts: readonly GeneratedArtifact[], scripts: Record<string, string>): GeneratedArtifact[] {
  return artifacts.filter((a) => typeof scripts[a.script] !== 'string');
}

/** 生成手段が不明な生成物について、承認前に尋ねる blocking 質問を作る（候補スクリプト + 手動更新） */
export function generationQuestions(unknown: readonly GeneratedArtifact[], candidates: readonly GenerationCandidate[], round: number): AskedQuestion[] {
  return unknown.slice(0, 3).map((a, i) => ({
    id: `${GENERATION_QUESTION_PREFIX}${round}-${i + 1}`,
    round,
    question: `【生成手段の確認】生成物「${a.path}」を再生成する方法が確定できません（提案されたスクリプト「${a.script}」は package.json にありません）。どのように更新しますか？\n理由: ${a.reason}`,
    decisionImpact: 'blocking',
    options: [
      ...candidates.slice(0, 3).map((c) => ({ value: c.script, label: `package.json の script「${c.script}」で再生成する（${c.command.slice(0, 60)}）` })),
      { value: MANUAL_GENERATION, label: '生成物の更新は今回の対象外にする（人が後で更新する）' }
    ],
    recommendation: candidates.length > 0 ? `候補「${candidates[0]!.script}」が出力先を含むなら、それを推奨。該当しなければ対象外にして承認後に手動で更新してください` : '対応する script が無いため、今回は対象外にして人が更新することを推奨します'
  }));
}

/** GEN- 質問への判断を素案に適用する（script の差し替え / 手動更新なら除外）。判断が無い項目はそのまま */
export function applyGenerationDecisions(proposal: TaskProposal, decisions: readonly DecisionRecord[]): TaskProposal {
  const byPath = new Map<string, string>();
  for (const d of decisions) {
    if (d.status !== 'active' || !d.topicKey.startsWith(GENERATION_QUESTION_PREFIX)) continue;
    const m = /生成物「([^」]+)」/.exec(d.question);
    if (m) byPath.set(m[1]!, d.chosen);
  }
  if (byPath.size === 0) return proposal;
  const artifacts: GeneratedArtifact[] = [];
  const outOfScope = [...proposal.outOfScope];
  for (const a of proposal.generatedArtifacts) {
    const chosen = byPath.get(a.path);
    if (chosen === undefined) artifacts.push(a);
    else if (chosen === MANUAL_GENERATION) {
      const note = `生成物 ${a.path} の更新（人が後で行う）`;
      if (!outOfScope.includes(note)) outOfScope.push(note);
    } else artifacts.push({ ...a, script: chosen });
  }
  return { ...proposal, generatedArtifacts: artifacts, outOfScope };
}
