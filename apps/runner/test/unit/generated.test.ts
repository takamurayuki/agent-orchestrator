import { describe, expect, it } from 'vitest';
import type { DecisionRecord, TaskProposal } from '@agent-orchestrator/contracts';
import { applyGenerationDecisions, detectGeneratedFiles, detectGenerationScripts, generationFacts, generationQuestions, unknownGenerationScripts } from '../../src/requirements/generated.js';

const scripts = { typecheck: 'tsc', lint: 'eslint .', 'test:run': 'vitest run', 'quality:report': 'node scripts/quality-report.mjs', 'gen:schemas': 'node scripts/gen-schemas.mjs', build: 'tsc -b' };
const files = ['package.json', 'scripts/quality-report.mjs', 'scripts/gen-schemas.mjs', 'docs/QUALITY_REPORT.md', 'docs/DECISIONS.md', 'src/schemas.generated.ts', 'README.md'];

const proposal = (over: Partial<TaskProposal> = {}): TaskProposal => ({
  title: 't',
  objective: 'o',
  requirements: ['r'],
  outOfScope: [],
  approach: 'a',
  acceptanceCriteria: [{ id: 'AC-001', given: 'g', when: 'w', then: 't' }],
  openItems: [],
  expectedChanges: ['scripts/quality-report.mjs'],
  conflictRisks: [],
  generatedArtifacts: [{ path: 'docs/QUALITY_REPORT.md', script: 'quality:report', reason: 'レポート生成器を変える' }],
  ...over
});
const decision = (question: string, chosen: string, topicKey = 'GEN-2-1', status: DecisionRecord['status'] = 'active'): DecisionRecord =>
  ({ topicKey, source: 'interview', kind: 'other', question, options: [], chosen, chosenLabel: chosen, rationale: '', consequence: '', evidence: [], relatedRequirements: [], decidedAt: 't', status, supersededBy: null, history: [], contradictionId: null }) as unknown as DecisionRecord;

describe('generated artifacts: repository facts (D-41)', () => {
  it('detects generation scripts by name or by an existing output file in the command, excluding plain build/test scripts', () => {
    const c = detectGenerationScripts(scripts, files);
    expect(c.map((x) => x.script).sort()).toEqual(['gen:schemas', 'quality:report']);
    expect(c.every((x) => !x.outputs.some((o) => o.startsWith('scripts/')))).toBe(true);
  });

  it('detects generated files from headers and links them to the package.json script that runs the generator', () => {
    const heads: Record<string, string> = {
      'docs/QUALITY_REPORT.md': '<!-- このファイルは scripts/quality-report.mjs により自動生成されます -->\n# 品質レポート',
      'docs/DECISIONS.md': '# 設計判断\n本文',
      'src/schemas.generated.ts': '// generated by scripts/gen-schemas.mjs — DO NOT EDIT',
      'README.md': '# Agent Orchestrator'
    };
    const hints = detectGeneratedFiles(files, (p) => heads[p] ?? null, scripts);
    expect(hints).toEqual([
      { path: 'docs/QUALITY_REPORT.md', generator: 'scripts/quality-report.mjs', script: 'quality:report' },
      { path: 'src/schemas.generated.ts', generator: 'scripts/gen-schemas.mjs', script: 'gen:schemas' }
    ]);
    const facts = generationFacts(detectGenerationScripts(scripts, files), hints);
    expect(facts.filter((f) => f.key === 'generation.script')).toHaveLength(2);
    const gf = facts.filter((f) => f.key === 'generated.file');
    expect(gf[0]!.value).toContain('script: quality:report');
    expect(gf[0]!.value).toContain('手で編集せず');
    expect(gf[0]!.confidence).toBe('confirmed');
  });

  it('a generated file whose generator is unknown is reported as inferred, never as a known script', () => {
    const hints = detectGeneratedFiles(['out.generated.json'], () => '{"a":1}', scripts);
    expect(hints).toEqual([{ path: 'out.generated.json', generator: null, script: null }]);
    expect(generationFacts([], hints)[0]).toMatchObject({ confidence: 'inferred' });
  });
});

describe('generated artifacts: unknown scripts become blocking questions, answers are applied mechanically', () => {
  it('a proposal whose script exists needs no question', () => {
    expect(unknownGenerationScripts(proposal().generatedArtifacts, scripts)).toEqual([]);
  });

  it('a script that is not in package.json yields a blocking GEN- question listing candidate scripts and a manual option; no shell command is offered', () => {
    const p = proposal({ generatedArtifacts: [{ path: 'docs/QUALITY_REPORT.md', script: 'report', reason: 'AI の推測' }] });
    const unknown = unknownGenerationScripts(p.generatedArtifacts, scripts);
    expect(unknown).toHaveLength(1);
    const qs = generationQuestions(unknown, detectGenerationScripts(scripts, files), 2);
    expect(qs).toHaveLength(1);
    expect(qs[0]).toMatchObject({ id: 'GEN-2-1', round: 2, decisionImpact: 'blocking' });
    expect(qs[0]!.question).toContain('生成物「docs/QUALITY_REPORT.md」');
    expect(qs[0]!.question).toContain('「report」は package.json にありません');
    expect(qs[0]!.options.map((o) => o.value)).toEqual(['quality:report', 'gen:schemas', 'manual']);
    for (const o of qs[0]!.options) expect(o.value).toMatch(/^[A-Za-z0-9_:.@/-]+$/);
  });

  it('a chosen script replaces the guessed one; "manual" removes the artifact and records it as out of scope', () => {
    const p = proposal({
      generatedArtifacts: [
        { path: 'docs/QUALITY_REPORT.md', script: 'report', reason: 'x' },
        { path: 'src/schemas.generated.ts', script: 'schemas', reason: 'y' }
      ]
    });
    const qs = generationQuestions(p.generatedArtifacts, [], 2);
    const applied = applyGenerationDecisions(p, [decision(qs[0]!.question, 'quality:report', 'GEN-2-1'), decision(qs[1]!.question, 'manual', 'GEN-2-2')]);
    expect(applied.generatedArtifacts).toEqual([{ path: 'docs/QUALITY_REPORT.md', script: 'quality:report', reason: 'x' }]);
    expect(applied.outOfScope).toContain('生成物 src/schemas.generated.ts の更新（人が後で行う）');
    // 失効した判断や GEN- 以外の判断は無視
    expect(applyGenerationDecisions(p, [decision(qs[0]!.question, 'quality:report', 'GEN-2-1', 'superseded'), decision('別の質問', 'a', 'Q-001')])).toEqual(p);
  });
});
